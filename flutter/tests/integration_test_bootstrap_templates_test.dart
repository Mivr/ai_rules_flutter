/// Guard for the `flutter_integration_test` bootstrap templates.
///
/// The three bootstrap programs are static files expanded per target with
/// `ctx.actions.expand_template`, so the Starlark unit tests can only see the
/// substitutions the rules pass, not the program text. This guard reads the
/// templates and the snippet module and pins what the unit tests used to
/// assert on the fully generated source: each platform program drives the
/// suite through `RemoteListener`, reports uncaught errors to the harness,
/// resolves the harness URL its own way, and carries every placeholder the
/// rules substitute. A placeholder deleted from a template would otherwise be
/// silently dropped by `expand_template`.
///
/// The guard discovers its inputs from the workspace root (the test's own
/// source file in `data`, or `BUILD_WORKSPACE_DIRECTORY` when set). Reading
/// undeclared files means Bazel cannot know when to re-run, so the target is
/// tagged `external` and never served a stale pass.
library;

import 'dart:io';

import 'package:test/test.dart';

/// Whether [root] is the rules_flutter workspace root.
bool _looksLikeRoot(String root) =>
    Directory('$root/flutter').existsSync() &&
    File('$root/MODULE.bazel').existsSync();

/// Workspace root the guard reads, or null when it cannot be resolved.
String? _workspaceRoot() {
  final fromEnv = Platform.environment['BUILD_WORKSPACE_DIRECTORY'];
  if (fromEnv != null && fromEnv.isNotEmpty && _looksLikeRoot(fromEnv)) {
    return fromEnv;
  }
  final anchor = Platform.environment['GUARD_ROOT_ANCHOR'];
  final srcdir = Platform.environment['TEST_SRCDIR'];
  if (anchor != null && anchor.isNotEmpty && srcdir != null) {
    try {
      var dir = File(
        File('$srcdir/$anchor').resolveSymbolicLinksSync(),
      ).parent;
      for (var i = 0; i < 8; i++) {
        if (_looksLikeRoot(dir.path)) return dir.path;
        dir = dir.parent;
      }
    } on FileSystemException {
      // Fall through to the loud failure below.
    }
  }
  return null;
}

/// The bootstrap template of one platform.
const _templates = <String, String>{
  'web': 'flutter/private/integration_test_bootstrap/web_bootstrap.dart.tpl',
  'linux':
      'flutter/private/integration_test_bootstrap/linux_bootstrap.dart.tpl',
  'android':
      'flutter/private/integration_test_bootstrap/android_bootstrap.dart.tpl',
};

/// Placeholders every program template substitutes.
const _commonPlaceholders = [
  '{binding_import}',
  '{test_import}',
  '{binding_decl}',
  '{binding_init}',
];

void main() {
  final root = _workspaceRoot();
  if (root == null) {
    test('bootstrap template guard discovers the workspace', () {
      fail(
        'BUILD_WORKSPACE_DIRECTORY does not point at the rules_flutter '
        'workspace; run this test unsandboxed (it is tagged no-sandbox) via '
        'bazel test //flutter/tests:integration_test_bootstrap_templates_test',
      );
    });
    return;
  }

  String read(String rel) => File('$root/$rel').readAsStringSync();

  for (final entry in _templates.entries) {
    final name = entry.key;
    final text = read(entry.value);
    test('$name bootstrap keeps the expected program', () {
      expect(text, contains('// GENERATED by flutter_integration_test'));
      expect(text, contains('RemoteListener.start'));
      expect(text, contains("'type': 'uncaughtError'"));
      for (final placeholder in _commonPlaceholders) {
        expect(
          text,
          contains(placeholder),
          reason: 'expand_template silently drops a missing placeholder',
        );
      }
    });
  }

  test('web bootstrap dials the page over a WebSocket', () {
    final text = read(_templates['web']!);
    expect(text, contains('_JSWebSocket'));
    expect(text, contains('/__flutter_integration_ws__'));
    expect(
      text,
      isNot(contains('FLUTTER_INTEGRATION_TEST_HARNESS_URL')),
      reason: 'the web bootstrap takes the harness URL from the page',
    );
    expect(
      text,
      isNot(contains('{harness_url_prologue}')),
      reason: 'only the dart:io bootstraps substitute a URL prologue',
    );
  });

  test('linux bootstrap reads the harness URL the prologue supplies', () {
    final text = read(_templates['linux']!);
    expect(text, contains('{harness_url_prologue}'));
    expect(text, contains('WebSocket.connect(wsUrl)'));
  });

  test('android bootstrap falls back to the adb-reverse port', () {
    final text = read(_templates['android']!);
    expect(text, contains('ws://127.0.0.1:38427/__flutter_integration_ws__'));
    expect(text, contains('WebSocket.connect(wsUrl)'));
    expect(
      text,
      isNot(contains('{harness_url_prologue}')),
      reason: 'the android bootstrap resolves its own URL',
    );
  });

  test('snippet module holds the one binding class and both prologues', () {
    final text = read(
      'flutter/private/integration_test_bootstrap_snippets.bzl',
    );
    expect(
      text,
      contains(
        'class _IntegrationTestBinding extends '
        'LiveTestWidgetsFlutterBinding',
      ),
    );
    expect(text, contains('LINUX_HARNESS_URL_PROLOGUE = '));
    expect(text, contains('IOS_HARNESS_URL_PROLOGUE = '));
    expect(text, contains('flutter_integration_test_harness_url'));
    expect(text, contains('Directory.systemTemp'));
    expect(text, contains('stderr.flush()'));
    expect(
      text,
      isNot(contains('ws://127.0.0.1')),
      reason: 'iOS never uses a fixed-port fallback',
    );
  });
}
