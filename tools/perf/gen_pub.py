#!/usr/bin/env python3
"""Generated-workspace pubspec files with the fixture's path deps stripped.

The hello_world fixture's pubspec.lock and pubspec.yaml name path
dependencies that exist only beside the fixture. The generated monorepo
copied them verbatim, so the Android app's plugin hub depends on spokes
whose paths are absent and the build's analysis fails. These helpers
strip those entries; the bench app imports none of them.
"""

import os

from gen_files import write_plain


def strip_pubspec_path_deps(text):
    """pubspec.yaml with path-dependency entries removed.

    A path dependency is an entry whose only value is ``path: ...``; the
    value names a directory that exists in the hello_world fixture but
    not in the generated workspace. Removing the entry and its value
    keeps every other dependency byte-identical.
    """
    lines = text.split("\n")
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.rstrip()
        if (stripped.startswith("  ") and not stripped.startswith("    ")
                and stripped.endswith(":")
                and i + 1 < len(lines)
                and lines[i + 1].lstrip().startswith("path:")):
            i += 1  # drop the entry line
            while i < len(lines) and lines[i].startswith("    "):
                i += 1  # drop the indented value block
            continue
        out.append(line)
        i += 1
    return "\n".join(out)


def strip_lock_path_packages(text):
    """pubspec.lock with ``source: path`` packages removed.

    Path packages name directories that exist in the hello_world fixture
    but not in the generated workspace. The Android plugin hub's
    ``all_android_plugin_libs`` depends on every such spoke, so a copied
    lock that names them fails the Android build's analysis with "path
    dependency ... does not exist". The generated app imports none of
    them, so dropping the entries is exact.
    """
    lines = text.split("\n")
    out = []
    block = []
    for line in lines:
        starts_block = (
            (line.startswith("  ") and not line.startswith("    ")
             and line.rstrip().endswith(":"))
            or (line and not line[0].isspace())
        )
        if starts_block and block:
            if "source: path" not in "\n".join(block):
                out.extend(block)
            block = []
        block.append(line)
    if block and "source: path" not in "\n".join(block):
        out.extend(block)
    return "\n".join(out)


_PUB_FILES = (
    ("pubspec.lock",
     "# Generated by pub\npackages: {}\nsdks:\n  dart: \">=3.9.0 <4.0.0\"\n",
     strip_lock_path_packages),
    ("pubspec.yaml",
     "name: bench_monorepo\nenvironment:\n  sdk: ^3.9.0\n",
     strip_pubspec_path_deps),
)


def copy_pub_files(out_dir, rules_flutter_dir):
    """Writes pubspec.lock and pubspec.yaml, fixture path deps stripped.

    Without the fixture (unit tests) a minimal fallback is written for
    each file, so generation never depends on the hello_world tree.
    """
    for file_name, fallback, strip in _PUB_FILES:
        src = os.path.join(
            rules_flutter_dir, "e2e", "hello_world", file_name)
        if os.path.isfile(src):
            with open(src, encoding="utf-8") as fh:
                write_plain(out_dir, file_name, strip(fh.read()))
        else:
            write_plain(out_dir, file_name, fallback)
