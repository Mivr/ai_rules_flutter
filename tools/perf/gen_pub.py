"""Generated-workspace pubspec files with the fixture's path deps stripped.

The hello_world fixture's pubspec.lock and pubspec.yaml name path
dependencies that exist only beside the fixture. The generated monorepo
copied them verbatim, so the Android app's plugin hub depends on spokes
whose paths are absent and the build's analysis fails. These helpers
strip those entries; the bench app imports none of them.
"""

import os
import re

from gen_files import write_plain


def strip_pubspec_path_deps(text):
    """pubspec.yaml with path-dependency entries removed.

    A path dependency is an entry whose only value is ``path: ...``; the
    value names a directory that exists in the hello_world fixture but
    not in the generated workspace. Removing the entry and its value
    keeps every other dependency byte-identical.
    """
    lines = text.split("\n")
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.rstrip()
        if (stripped.startswith("  ") and not stripped.startswith("    ")
                and stripped.endswith(":")
                and i + 1 < len(lines)
                and lines[i + 1].lstrip().startswith("path:")):
            i += 1  # drop the entry line
            while i < len(lines) and lines[i].startswith("    "):
                i += 1  # drop the indented value block
            continue
        out.append(line)
        i += 1
    return "\n".join(out)


def strip_lock_path_packages(text):
    """pubspec.lock with ``source: path`` packages removed.

    Path packages name directories that exist in the hello_world fixture
    but not in the generated workspace. The Android plugin hub's
    ``all_android_plugin_libs`` depends on every such spoke, so a copied
    lock that names them fails the Android build's analysis with "path
    dependency ... does not exist". The generated app imports none of
    them, so dropping the entries is exact.
    """
    lines = text.split("\n")
    out = []
    block = []
    for line in lines:
        starts_block = (
            (line.startswith("  ") and not line.startswith("    ")
             and line.rstrip().endswith(":"))
            or (line and not line[0].isspace())
        )
        if starts_block and block:
            if "source: path" not in "\n".join(block):
                out.extend(block)
            block = []
        block.append(line)
    if block and "source: path" not in "\n".join(block):
        out.extend(block)
    return "\n".join(out)


_PUB_FILES = (
    ("pubspec.lock",
     "# Generated by pub\npackages: {}\nsdks:\n  dart: \">=3.9.0 <4.0.0\"\n",
     strip_lock_path_packages),
    ("pubspec.yaml",
     "name: bench_monorepo\nenvironment:\n  sdk: ^3.9.0\n",
     strip_pubspec_path_deps),
)


def copy_pub_files(out_dir, rules_flutter_dir):
    """Writes pubspec.lock and pubspec.yaml, fixture path deps stripped.

    Without the fixture (unit tests) a minimal fallback is written for
    each file, so generation never depends on the hello_world tree.
    """
    for file_name, fallback, strip in _PUB_FILES:
        src = os.path.join(
            rules_flutter_dir, "e2e", "hello_world", file_name)
        if os.path.isfile(src):
            with open(src, encoding="utf-8") as fh:
                write_plain(out_dir, file_name, strip(fh.read()))
        else:
            write_plain(out_dir, file_name, fallback)


def _strip_comments(text):
    """MODULE text with ``#`` comments removed, string literals intact."""
    out = []
    quote = None
    i = 0
    while i < len(text):
        ch = text[i]
        if quote:
            out.append(ch)
            if ch == "\\" and i + 1 < len(text):
                i += 1
                out.append(text[i])
            elif ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
            out.append(ch)
        elif ch == "#":
            while i < len(text) and text[i] != "\n":
                i += 1
            continue
        else:
            out.append(ch)
        i += 1
    return "".join(out)


_LOCK_FILE_RE = re.compile(r"(?<![\w.])lock_file\s*=\s*\"([^\"]*)\"")
_ROOT_PREFIXES = ("@@//", "@//", "//")


def lock_file_rel_path(label):
    """Workspace-relative path of a root-workspace label, else None.

    External labels (``@repo//...``) return None. A malformed, empty,
    absolute or escaping root label raises ValueError naming it.
    """
    if label.startswith("@") and not label.startswith(_ROOT_PREFIXES):
        return None
    body = label
    for prefix in _ROOT_PREFIXES:
        if label.startswith(prefix):
            body = label[len(prefix) - 2:]
            break
    if body.startswith(":"):
        body = "//" + body
    if not body.startswith("//") or body.count(":") != 1:
        raise ValueError("malformed lock_file label: %r" % label)
    pkg, target = body[2:].split(":")
    rel = pkg + "/" + target if pkg else target
    parts = rel.split("/")
    if (not target or "\\" in rel or rel.startswith("/")
            or any(p in ("", ".", "..") for p in parts)):
        raise ValueError("invalid lock_file label: %r" % label)
    return rel


def stage_lock_files(out_dir, rules_flutter_dir, module_text):
    """Copies each workspace-local ``lock_file`` into the workspace.

    The lockfiles come from the hello_world fixture, byte for byte. A
    declared lockfile missing from the fixture raises ValueError.
    """
    seen = {}
    for label in _LOCK_FILE_RE.findall(_strip_comments(module_text)):
        rel = lock_file_rel_path(label)
        if rel is not None:
            seen.setdefault(rel, label)
    fixture = os.path.join(rules_flutter_dir, "e2e", "hello_world")
    for rel, label in seen.items():
        src = os.path.join(fixture, *rel.split("/"))
        if not os.path.isfile(src):
            raise ValueError(
                "lock_file %r (%s) needs fixture %s, which is missing"
                % (label, rel, src))
        dest = os.path.join(out_dir, *rel.split("/"))
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(src, "rb") as fh:
            data = fh.read()
        with open(dest, "wb") as fh:
            fh.write(data)


def copy_pub_and_lock_files(out_dir, rules_flutter_dir, module_text):
    """Writes the pub files and stages the MODULE's local lockfiles."""
    copy_pub_files(out_dir, rules_flutter_dir)
    stage_lock_files(out_dir, rules_flutter_dir, module_text)
